<?php

/**
 * Regenerates docker/preload-classes.txt: handles a representative request mix in-process and prints
 * the class of every Composer-mapped file PHP loaded. Run inside a local container (it reserves one
 * ticket in the newest event, so never against a shared database):
 *
 *   docker compose exec ticketing-api php docker/preload-trace.php > apps/ticketing-api/docker/preload-classes.txt
 */

use App\Services\InventoryAdmin;
use Illuminate\Contracts\Http\Kernel;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

$base = dirname(__DIR__);
require $base.'/vendor/autoload.php';
$app = require $base.'/bootstrap/app.php';
$kernel = $app->make(Kernel::class);
$kernel->bootstrap();

$category = DB::selectOne('SELECT c.id, c.event_id FROM ticket_categories c JOIN events e ON e.id = c.event_id
    WHERE c.capacity - c.held - c.sold > 0 ORDER BY e.created_at DESC LIMIT 1')
    ?? (object) app(InventoryAdmin::class)->createEvent('preload trace', [['name' => 'GA', 'price_cents' => 100, 'capacity' => 10]])
        ->categories->first()->only(['id', 'event_id']);

$json = ['HTTP_ACCEPT' => 'application/json', 'CONTENT_TYPE' => 'application/json'];
$requests = [
    Request::create("/api/events/{$category->event_id}/availability", 'GET', server: $json),
    Request::create("/api/events/{$category->event_id}", 'GET', server: $json),
    Request::create('/api/reservations', 'POST', server: $json + ['HTTP_IDEMPOTENCY_KEY' => 'preload-trace-'.bin2hex(random_bytes(6))],
        content: json_encode(['category_id' => $category->id, 'quantity' => 1, 'customer_ref' => 'preload-trace'])),
    Request::create('/api/reservations', 'POST', server: $json, content: '{}'),                       // 400
    Request::create('/api/reservations', 'POST', server: $json + ['HTTP_IDEMPOTENCY_KEY' => 'preload-trace-invalid'], content: '{}'), // 422
    Request::create('/api/events/00000000-0000-0000-0000-000000000000/availability', 'GET', server: $json), // 404
    Request::create('/health', 'GET', server: $json),
];
foreach ($requests as $request) {
    $response = $kernel->handle($request);
    $kernel->terminate($request, $response);
}

$classByFile = array_flip(require $base.'/vendor/composer/autoload_classmap.php');
echo "# Generated by docker/preload-trace.php; one class per line, loaded by docker/preload.php.\n";
foreach (get_included_files() as $file) {
    if (isset($classByFile[$file])) {
        echo $classByFile[$file], "\n";
    }
}
